/**
 * Embed Drizzle Kit migrations (migrations/<dialect>/*.sql + meta/_journal.json)
 * into src/migrations/generated.ts so `migrate()` works without a filesystem
 * (Cloudflare Workers) and without drizzle-kit at runtime.
 *
 *   bun run db:generate   # drizzle-kit generate (both dialects) + this script
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '..');

function load(dialect: 'sqlite' | 'pg'): Array<{ tag: string; sql: string }> {
  const dir = join(root, 'migrations', dialect);
  const journal = JSON.parse(readFileSync(join(dir, 'meta', '_journal.json'), 'utf8')) as {
    entries: Array<{ idx: number; tag: string }>;
  };
  return journal.entries
    .sort((a, b) => a.idx - b.idx)
    .map((e) => ({ tag: e.tag, sql: readFileSync(join(dir, `${e.tag}.sql`), 'utf8') }));
}

const render = (name: string, ms: Array<{ tag: string; sql: string }>) =>
  `export const ${name}: SqlMigration[] = [\n${ms
    .map(
      (m) => `  {\n    tag: ${JSON.stringify(m.tag)},\n    sql: ${JSON.stringify(m.sql)},\n  },\n`,
    )
    .join('')}];\n`;

const out = `// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by scripts/embed-migrations.ts from migrations/ (Drizzle Kit output). Do not edit.
import type { SqlMigration } from '../migrate.ts';

${render('sqliteMigrations', load('sqlite'))}
${render('pgMigrations', load('pg'))}`;

const target = join(root, 'src', 'migrations', 'generated.ts');
writeFileSync(target, out);
Bun.spawnSync(['bunx', 'biome', 'format', '--write', target], { stdout: 'ignore' });
console.log('wrote src/migrations/generated.ts');
