/**
 * Project files written by `create-beamhop --cf`. The wrangler.toml mirrors
 * deploy/cloudflare/wrangler.toml (the runtime-cf template) with real names and ids.
 */

/** Default npm spec for the Worker bundle (see README: assumes a published package). */
export const DEFAULT_RUNTIME_SPEC = '@beamhop/runtime-cf@latest';
export const RUNTIME_PACKAGE = '@beamhop/runtime-cf';
/** Where `wrangler d1 migrations apply` finds the SQL (shipped with @beamhop/storage-sql). */
export const MIGRATIONS_DIR = 'node_modules/@beamhop/storage-sql/migrations/sqlite';

export interface ProjectSettings {
  /** Worker name (slug). */
  worker: string;
  /** Relay name shown in apps. */
  relayName: string;
  /** Custom domain, or undefined for workers.dev. */
  domain?: string;
  /** Owner public key (hex), optional. */
  ownerHex?: string;
  d1Name: string;
  d1Id: string;
  bucket: string;
}

/** Split an npm spec like `@scope/name@1.2.3` or a tarball URL into package.json dependency form. */
export function dependencyFor(spec: string): [name: string, version: string] {
  if (/^(https?:|file:|git\+|github:)/.test(spec) || spec.endsWith('.tgz')) {
    return [RUNTIME_PACKAGE, spec];
  }
  const at = spec.lastIndexOf('@');
  if (at > 0) return [spec.slice(0, at), spec.slice(at + 1) || 'latest'];
  return [spec, 'latest'];
}

export function packageJson(s: Pick<ProjectSettings, 'worker'>, runtimeSpec: string): string {
  const [name, version] = dependencyFor(runtimeSpec);
  const pkg = {
    name: s.worker,
    private: true,
    type: 'module',
    scripts: {
      deploy: 'wrangler deploy',
      dev: 'wrangler dev',
      migrate: `wrangler d1 migrations apply ${s.worker} --remote`,
    },
    dependencies: { [name]: version },
    devDependencies: { wrangler: '^4.40.0' },
  };
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

export function beamhopConfig(s: Pick<ProjectSettings, 'relayName' | 'domain' | 'ownerHex'>) {
  const info: Record<string, string> = { name: s.relayName, description: '' };
  if (s.ownerHex) info.pubkey = s.ownerHex;
  return {
    storage: { driver: 'd1' },
    blobStorage: { driver: 'r2' },
    relays: [{ id: 'main', hosts: s.domain ? [s.domain] : ['*'], info }],
    plugins: [],
  };
}

const q = (s: string) => JSON.stringify(s);

export function wranglerToml(s: ProjectSettings): string {
  const routes = s.domain
    ? `\n# Your own domain (its DNS zone must be on this Cloudflare account).\nroutes = [{ pattern = ${q(s.domain)}, custom_domain = true }]\n`
    : '\n# Served on the free <name>.<your-subdomain>.workers.dev address.\nworkers_dev = true\n';
  return `# SPDX-License-Identifier: AGPL-3.0-or-later
# Generated by create-beamhop. Re-running \`npm create beamhop -- --cf\` rewrites this file.
# Beamhop on Cloudflare: Worker + Durable Objects (WebSockets) + D1 (data) + R2 (files).

name = ${q(s.worker)}
main = "build/entry.ts"
compatibility_date = "2025-09-01"
${routes}
# Generates build/entry.ts: a static import map of built-in packages and the plugins
# enabled in beamhop.config.json (Workers cannot load code at runtime).
[build]
command = "npx beamhop-cf-build --config beamhop.config.json --out build/entry.ts"

# One RelayRoom object per relay shard; WebSockets use the Hibernation API.
[[durable_objects.bindings]]
name = "RELAY_ROOM"
class_name = "RelayRoom"

[[migrations]]
tag = "v1"
new_sqlite_classes = ["RelayRoom"]

[[d1_databases]]
binding = "DB"
database_name = ${q(s.d1Name)}
database_id = ${q(s.d1Id)}
migrations_dir = ${q(MIGRATIONS_DIR)}

[[r2_buckets]]
binding = "BLOBS"
bucket_name = ${q(s.bucket)}

# Optional: Cloudflare Images for thumbnails/resizing. Uncomment to enable.
# [images]
# binding = "IMAGES"

# Maintenance jobs (retention, expiry, digests) run from this one-minute cron.
[triggers]
crons = ["* * * * *"]

[vars]
RELAY_SHARDS = "1"
LOG_LEVEL = "info"
QUERY_BUDGET_MS = "2000"

[observability]
enabled = true
`;
}

