/** Sum Prometheus text-format samples by metric name. */
export function parsePrometheus(text: string): Map<string, number> {
  const out = new Map<string, number>();
  for (const line of text.split('\n')) {
    const l = line.trim();
    if (!l || l.startsWith('#')) continue;
    const m = /^([a-zA-Z_:][a-zA-Z0-9_:]*)(\{[^}]*\})?\s+(\S+)/.exec(l);
    if (!m) continue;
    const v = Number(m[3]);
    if (!Number.isFinite(v)) continue;
    out.set(m[1] as string, (out.get(m[1] as string) ?? 0) + v);
  }
  return out;
}

const first = (m: Map<string, number>, names: string[]) => {
  for (const n of names) if (m.has(n)) return m.get(n);
  return undefined;
};

export interface LitestreamStatus {
  reachable: boolean;
  /** Seconds the replica has been behind local writes (0 = caught up). */
  lagSeconds: number;
  syncErrors: number;
  lastSampleAt?: number;
  error?: string;
}

/**
 * Lag heuristic (Litestream exposes counters, not a "last replicated at"
 * gauge): when local WAL progress advances while replica progress does not,
 * the replica is "behind since" that sample; any replica progress resets it.
 */
export class LitestreamMonitor {
  private prevDb?: number;
  private prevReplica?: number;
  private behindSince?: number;
  private baseErrors?: number;
  status: LitestreamStatus = { reachable: false, lagSeconds: 0, syncErrors: 0 };

  constructor(
    private readonly fetchImpl: (url: string, init?: RequestInit) => Promise<Response>,
    private readonly now: () => number,
  ) {}

  async sample(url: string): Promise<LitestreamStatus> {
    const now = this.now();
    let text: string;
    try {
      const res = await this.fetchImpl(url, { signal: AbortSignal.timeout(5000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      text = await res.text();
    } catch (err) {
      this.status = {
        reachable: false,
        lagSeconds: this.behindSince !== undefined ? now - this.behindSince : 0,
        syncErrors: this.status.syncErrors,
        lastSampleAt: now,
        error: err instanceof Error ? err.message : String(err),
      };
      return this.status;
    }
    const m = parsePrometheus(text);
    const db = first(m, ['litestream_total_wal_bytes', 'litestream_wal_size', 'litestream_txid']);
    const replica =
      first(m, ['litestream_replica_operation_bytes']) ??
      ((m.get('litestream_replica_wal_index') ?? 0) * 2 ** 32 +
        (m.get('litestream_replica_wal_offset') ?? 0) ||
        undefined);
    const errors = first(m, ['litestream_sync_error_n', 'litestream_sync_error_count']) ?? 0;
    this.baseErrors ??= errors;

    const dbMoved = db !== undefined && this.prevDb !== undefined && db !== this.prevDb;
    const replicaMoved =
      replica !== undefined && this.prevReplica !== undefined && replica !== this.prevReplica;
    if (replicaMoved) this.behindSince = undefined;
    else if (dbMoved) this.behindSince ??= now;
    this.prevDb = db;
    this.prevReplica = replica;

    this.status = {
      reachable: true,
      lagSeconds: this.behindSince !== undefined ? now - this.behindSince : 0,
      syncErrors: errors - this.baseErrors,
      lastSampleAt: now,
    };
    return this.status;
  }
}

export function litestreamHealth(
  s: LitestreamStatus,
  cfg: LifecycleConfig['litestream'],
): HealthResult {
  const technical = `litestream reachable=${s.reachable} lagSeconds=${s.lagSeconds} syncErrors=${s.syncErrors} metrics=${cfg.metricsUrl}`;
  if (s.lastSampleAt === undefined)
    return { score: 90, status: 'ok', message: 'Checking replication to the standby…', technical };
  if (!s.reachable)
    return {
      score: 20,
      status: 'critical',
      message: 'Replication to the standby is not running',
      technical: `${technical} error=${s.error ?? ''}`,
    };
  if (s.lagSeconds >= cfg.lagCriticalSeconds)
    return {
      score: 30,
      status: 'critical',
      message: `The standby is ${Math.round(s.lagSeconds / 60)} minutes behind`,
      technical,
    };
  if (s.lagSeconds >= cfg.lagWarnSeconds || s.syncErrors > 0)
    return {
      score: 60,
      status: 'warn',
      message:
        s.syncErrors > 0
          ? 'Replication had errors recently'
          : `The standby is ${s.lagSeconds} seconds behind`,
      technical,
    };
  return { score: 100, status: 'ok', message: 'The standby is up to date', technical };
}
