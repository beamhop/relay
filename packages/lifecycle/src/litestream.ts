/**
 * Litestream (§12.11, continuous SQLite replication for VM installs):
 * `generateLitestreamConfig()` writes `litestream.yml` from Beamhop config and
 * `LitestreamMonitor` scrapes Litestream's Prometheus endpoint to report
 * replication lag. See `docs/high-availability.md` for active-passive failover.
 */
import type { BeamhopConfig, HealthResult } from '@beamhop/core';
import type { LifecycleConfig } from './settings.ts';

type Replica = NonNullable<BeamhopConfig['backups']['target']>;

export interface LitestreamOptions {
  /** SQLite file to replicate (default: storage.url or `<dataDir>/db/beamhop.sqlite`). */
  dbPath?: string;
  /** Replica target (default: modules.lifecycle.litestream.replica, else backups.target). */
  replica?: Replica;
  /** Path/prefix inside the bucket. */
  path?: string;
  /** Metrics listen address, e.g. `127.0.0.1:9090` (empty string disables). */
  addr?: string;
  syncInterval?: string;
  snapshotInterval?: string;
  retention?: string;
  /** Write keys into the file instead of `${LITESTREAM_ACCESS_KEY_ID}` references. */
  inlineSecrets?: boolean;
}

const q = (s: string) => JSON.stringify(s);

export function sqlitePathOf(config: BeamhopConfig): string {
  if (config.storage.url) return config.storage.url.replace(/^(sqlite|file):(\/\/)?/, '');
  return `${config.node.dataDir.replace(/\/+$/, '')}/db/beamhop.sqlite`;
}

function addrOf(metricsUrl: string | undefined): string {
  if (!metricsUrl) return '127.0.0.1:9090';
  try {
    const u = new URL(metricsUrl);
    return `${u.hostname}:${u.port || '9090'}`;
  } catch {
    return '127.0.0.1:9090';
  }
}

/** Build `litestream.yml` (YAML) for this node. Throws when storage is not SQLite. */
export function generateLitestreamConfig(
  config: BeamhopConfig,
  opts: LitestreamOptions = {},
): string {
  if (config.storage.driver !== 'sqlite')
    throw new Error('Litestream only replicates SQLite databases (storage.driver is not sqlite)');
  const lit = (config.modules.lifecycle as Partial<LifecycleConfig> | undefined)?.litestream;
  // `backups.target` defaults to a local folder, which is no replica: only buckets count there.
  const fromBackups =
    config.backups.target && !['fs', 'memory'].includes(config.backups.target.driver)
      ? config.backups.target
      : undefined;
  const replica = opts.replica ?? lit?.replica ?? fromBackups;
  if (!replica || replica.driver === 'memory')
    throw new Error('Choose where the replica goes (S3, R2, GCS or a folder) first');
  const path = opts.path ?? lit?.path ?? 'beamhop/db';
  const addr = opts.addr ?? addrOf(lit?.metricsUrl);
  const secret = (value: string | undefined, env: string) =>
    opts.inlineSecrets && value ? q(value) : q(`\${${env}}`);

  const out: string[] = [
    '# Generated by Beamhop — Litestream continuous replication (PLAN §12.11).',
    '# Run next to Beamhop:  litestream replicate -config /etc/litestream.yml',
    '# Restore on a standby: litestream restore -config /etc/litestream.yml -if-replica-exists <db path>',
  ];
  if (addr) out.push(`addr: ${q(addr)}`);
  out.push('dbs:', `  - path: ${q(opts.dbPath ?? sqlitePathOf(config))}`, '    replicas:');
  const r = (k: string, v: string) => out.push(`        ${k}: ${v}`);
  out.push(`      - name: ${q('primary')}`);
  switch (replica.driver) {
    case 'fs':
      r('type', q('file'));
      r('path', q(replica.path ?? `${config.node.dataDir.replace(/\/+$/, '')}/replica`));
      break;
    case 'gcs':
      if (!replica.accessKeyId) {
        r('type', q('gcs'));
        r('bucket', q(replica.bucket ?? ''));
        r('path', q(path));
        out.push(
          '        # Credentials: set GOOGLE_APPLICATION_CREDENTIALS to a service account key.',
        );
        break;
      }
      // HMAC keys: use the S3-compatible XML API.
      r('type', q('s3'));
      r('bucket', q(replica.bucket ?? ''));
      r('path', q(path));
      r('endpoint', q(replica.endpoint ?? 'https://storage.googleapis.com'));
      r('region', q(replica.region ?? 'auto'));
      r('access-key-id', secret(replica.accessKeyId, 'LITESTREAM_ACCESS_KEY_ID'));
      r('secret-access-key', secret(replica.secretAccessKey, 'LITESTREAM_SECRET_ACCESS_KEY'));
      break;
    case 'r2':
    case 's3': {
      r('type', q('s3'));
      r('bucket', q(replica.bucket ?? ''));
      r('path', q(path));
      if (replica.endpoint) r('endpoint', q(replica.endpoint));
      else if (replica.driver === 'r2')
        out.push(
          '        # endpoint: "https://<account-id>.r2.cloudflarestorage.com"  (required for R2)',
        );
      r('region', q(replica.region ?? (replica.driver === 'r2' ? 'auto' : 'us-east-1')));
      if (replica.driver === 's3' && replica.endpoint) r('force-path-style', 'true');
      r('access-key-id', secret(replica.accessKeyId, 'LITESTREAM_ACCESS_KEY_ID'));
      r('secret-access-key', secret(replica.secretAccessKey, 'LITESTREAM_SECRET_ACCESS_KEY'));
      break;
    }
  }
  r('sync-interval', q(opts.syncInterval ?? lit?.syncInterval ?? '1s'));
  r('snapshot-interval', q(opts.snapshotInterval ?? lit?.snapshotInterval ?? '24h'));
  r('retention', q(opts.retention ?? lit?.retention ?? '72h'));
  return `${out.join('\n')}\n`;
}

