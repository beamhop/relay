describe('first backup when backups are turned on', () => {
  test('backups.setup (disabled → enabled) makes the first backup right away', async () => {
    const t = await setup({
      modules: [
        {
          id: 'fake-admin-config',
          register(kernel) {
            kernel.provide('admin.config', {
              apply: (next: unknown) => kernel.applyConfig(next as never),
            });
          },
        },
      ],
    });
    expect(t.svc.backupInProgress()).toBe(false);
    const { result } = await t.act(
      'backups.setup',
      { enabled: true, schedule: 'daily', keep: 3 },
      null,
    );
    expect((result.output as { committed: boolean }).committed).toBe(true);
    expect(t.svc.backupInProgress()).toBe(true);
    await t.svc.idle();
    expect(t.svc.backupInProgress()).toBe(false);
    const last = await t.svc.lastBackup();
    expect(last?.ok).toBe(true);
    expect(await t.svc.backups.due()).toBe(false);
  });

  test('a plain config change turns it on too; staying on or turning off does not back up', async () => {
    const t = await setup();
    const cfg = t.kernel.config();
    await t.kernel.applyConfig({ ...cfg, backups: { ...cfg.backups, enabled: true } });
    expect(t.svc.backupInProgress()).toBe(true);
    await t.svc.idle();
    const first = await t.svc.lastBackup();
    expect(first?.ok).toBe(true);
    t.ports.clock.advance(60);
    const on = t.kernel.config();
    await t.kernel.applyConfig({ ...on, backups: { ...on.backups, keep: 9 } });
    expect(t.svc.backupInProgress()).toBe(false);
    await t.kernel.applyConfig({ ...on, backups: { ...on.backups, enabled: false } });
    expect(t.svc.backupInProgress()).toBe(false);
    expect((await t.svc.lastBackup())?.at).toBe(first?.at as number);
  });

  test('a failing first backup lands in lastBackup with the reason', async () => {
    const t = await setup({ target: null });
    const cfg = t.kernel.config();
    await t.kernel.applyConfig({
      ...cfg,
      backups: { ...cfg.backups, enabled: true, target: { driver: 's3' } },
    } as never);
    await t.svc.idle();
    const last = await t.svc.lastBackup();
    expect(last?.ok).toBe(false);
    expect(last?.error).toBeTruthy();
  });
});

describe('litestream', () => {
  test('config generation snapshot (R2 replica, secrets as env references)', () => {
    const config = parseConfig({
      node: { dataDir: '/var/lib/beamhop' },
      storage: { driver: 'sqlite' },
      modules: {
        lifecycle: {
          litestream: {
            replica: {
              driver: 'r2',
              bucket: 'relay-replica',
              endpoint: 'https://acct.r2.cloudflarestorage.com',
              accessKeyId: 'AKIA',
              secretAccessKey: 'shh',
            },
          },
        },
      },
    });
    expect(generateLitestreamConfig(config)).toBe(
      `# Generated by Beamhop — Litestream continuous replication (PLAN §12.11).
# Run next to Beamhop:  litestream replicate -config /etc/litestream.yml
# Restore on a standby: litestream restore -config /etc/litestream.yml -if-replica-exists <db path>
addr: "127.0.0.1:9090"
dbs:
  - path: "/var/lib/beamhop/db/beamhop.sqlite"
    replicas:
      - name: "primary"
        type: "s3"
        bucket: "relay-replica"
        path: "beamhop/db"
        endpoint: "https://acct.r2.cloudflarestorage.com"
        region: "auto"
        access-key-id: "\${LITESTREAM_ACCESS_KEY_ID}"
        secret-access-key: "\${LITESTREAM_SECRET_ACCESS_KEY}"
        sync-interval: "1s"
        snapshot-interval: "24h"
        retention: "72h"
`,
    );
  });

  test('S3 from backups.target, GCS service account, inline secrets, errors', () => {
    const s3 = parseConfig({
      storage: { url: 'sqlite:///data/x.sqlite' },
      backups: {
        target: {
          driver: 's3',
          bucket: 'b',
          region: 'eu-west-1',
          accessKeyId: 'K',
          secretAccessKey: 'S',
        },
      },
    });
    const yaml = generateLitestreamConfig(s3, { inlineSecrets: true, addr: '' });
    expect(yaml).toContain('path: "/data/x.sqlite"');
    expect(yaml).toContain('region: "eu-west-1"');
    expect(yaml).toContain('access-key-id: "K"');
    expect(yaml).not.toContain('addr:');

    const gcs = parseConfig({ backups: { target: { driver: 'gcs', bucket: 'g' } } });
    expect(generateLitestreamConfig(gcs)).toContain('type: "gcs"');

    expect(() => generateLitestreamConfig(parseConfig({}))).toThrow(/Choose where/);
    expect(() =>
      generateLitestreamConfig(
        parseConfig({ storage: { driver: 'postgres', url: 'postgres://x' } }),
      ),
    ).toThrow(/only replicates SQLite/);
  });

  test('metrics → replication lag', async () => {
    let body = '';
    let up = true;
    let now = 1000;
    const mon = new LitestreamMonitor(
      async () => (up ? new Response(body) : Promise.reject(new Error('ECONNREFUSED'))),
      () => now,
    );
    const metrics = (db: number, replica: number, errors = 0) =>
      `# HELP x\nlitestream_total_wal_bytes{db="/d"} ${db}\nlitestream_replica_operation_bytes{db="/d",name="primary",operation="PUT"} ${replica}\nlitestream_sync_error_count{db="/d"} ${errors}\n`;

    body = metrics(100, 100);
    expect((await mon.sample('http://x/metrics')).lagSeconds).toBe(0);
    now += 30;
    body = metrics(200, 100);
    expect((await mon.sample('http://x/metrics')).lagSeconds).toBe(0);
    now += 90;
    body = metrics(300, 100);
    const s = await mon.sample('http://x/metrics');
    expect(s.lagSeconds).toBe(90);
    now += 10;
    body = metrics(300, 300, 2);
    const caught = await mon.sample('http://x/metrics');
    expect(caught).toMatchObject({ reachable: true, lagSeconds: 0, syncErrors: 2 });
    up = false;
    expect((await mon.sample('http://x/metrics')).reachable).toBe(false);
    expect(parsePrometheus('a{b="1"} 2\na 3\n# c\nbad').get('a')).toBe(5);
  });

  test('health check and card when enabled', async () => {
    const t = await setup({
      lifecycle: { litestream: { enabled: true } },
      options: { fetch: async () => Promise.reject(new Error('down')) },
    });
    const check = t.kernel.health.find((h) => h.id === 'lifecycle.litestream') as HealthCheck;
    expect(check.weight).toBe(2);
    await t.ports.scheduler.tick(JOBS.litestream);
    expect((await check.run(null)).status).toBe('critical');
    const cards = (await t.kernel.cards[0]?.cards(null)) ?? [];
    expect(cards.find((c) => c.id === 'lifecycle.litestream')?.playbook).toBe('lifecycle.failover');
    expect(t.kernel.playbooks.some((p) => p.id === 'lifecycle.failover')).toBe(true);
  });

  test('disabled → zero weight', async () => {
    const t = await setup();
    const check = t.kernel.health.find((h) => h.id === 'lifecycle.litestream') as HealthCheck;
    expect(check.weight).toBe(0);
  });
});

describe('known-good', () => {
  function fakeConfigService() {
    const calls: unknown[] = [];
    return {
      calls,
      module: {
        id: 'fake-admin',
        register(kernel: { provide: (n: string, s: unknown) => void }) {
          kernel.provide('admin.config', {
            async markKnownGood(target?: unknown) {
              calls.push(target);
              return 7;
            },
          });
        },
      },
    };
  }

  test('marks after 5 healthy minutes; critical health resets the timer', async () => {
    const fake = fakeConfigService();
    const t = await setup({ modules: [fake.module] });
    let critical = false;
    t.kernel.health.push({
      id: 'test.flaky',
      subsystem: 'relay',
      weight: 1,
      run: async () => ({
        score: critical ? 0 : 100,
        status: critical ? 'critical' : 'ok',
        message: '',
      }),
    });
    t.ports.clock.advance(120);
    await t.ports.scheduler.tick(JOBS.knownGood);
    expect(fake.calls.length).toBe(0);
    critical = true;
    t.ports.clock.advance(120);
    await t.ports.scheduler.tick(JOBS.knownGood);
    critical = false;
    t.ports.clock.advance(240);
    await t.ports.scheduler.tick(JOBS.knownGood);
    expect(fake.calls.length).toBe(0);
    t.ports.clock.advance(61);
    await t.ports.scheduler.tick(JOBS.knownGood);
    expect(fake.calls.length).toBe(1);
    expect(t.svc.knownGood.state).toBe('marked');
    expect(t.ports.scheduler.jobs.has(JOBS.knownGood)).toBe(false);
    expect(await t.ports.docs.get('lifecycle.boot', 'known-good')).toMatchObject({ revision: 7 });
  });

  test('never marks in safe mode', async () => {
    const fake = fakeConfigService();
    const t = await setup({ modules: [fake.module] });
    t.kernel.provide('runtime', { name: 'bun', safe: true });
    t.ports.clock.advance(600);
    expect(await t.svc.knownGood.tick()).toBe('skipped');
    expect(fake.calls.length).toBe(0);
  });
});

describe('user export', () => {
  test('NDJSON stream of events + blob manifest, and the action', async () => {
    const t = await setup();
    const me = makeKey();
    const other = makeKey();
    for (let i = 0; i < 7; i++)
      await t.ports.events.save('main', t.ev(me, { created_at: t.ports.clock.now() - i }));
    await t.ports.events.save('main', t.ev(other));
    await t.ports.blobIndex.addOwner({
      relayId: 'main',
      sha256: 'c'.repeat(64),
      pubkey: me.pk,
      size: 5,
      type: 'image/jpeg',
      uploadedAt: 10,
    });
    const text = await new Response(t.svc.exportUserData('main', me.pk, { pageSize: 3 })).text();
    const lines = text
      .trimEnd()
      .split('\n')
      .map((l) => JSON.parse(l));
    expect(lines[0]).toMatchObject({ type: 'export', format: USER_EXPORT_FORMAT, pubkey: me.pk });
    expect(lines.filter((l) => l.type === 'event').length).toBe(7);
    expect(lines.every((l) => l.type !== 'event' || l.event.pubkey === me.pk)).toBe(true);
    expect(lines.find((l) => l.type === 'blob')).toMatchObject({ sha256: 'c'.repeat(64) });
    expect(lines.at(-1)).toEqual({ type: 'end', events: 7, blobs: 1 });

    const { result } = await t.act('lifecycle.export-user', { pubkey: me.pk, maxEvents: 5 });
    expect(result.output).toMatchObject({ events: 5, blobs: 1, truncated: true });
  });
});
