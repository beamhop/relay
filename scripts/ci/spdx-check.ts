/**
 * SPDX header check (PLAN §17, CLAUDE.md rule 7): every Beamhop source file starts with
 * `SPDX-License-Identifier: AGPL-3.0-or-later` (within the first lines, any comment style;
 * after a shebang is fine).
 *
 *   bun scripts/ci/spdx-check.ts            # list files without the header, exit 1 if any
 *   bun scripts/ci/spdx-check.ts --fix      # add the header (outside packages/pwa and team-client)
 *
 * Scanned: .ts/.tsx/.js/.mjs/.cjs/.svelte under packages/<pkg>/{src,test,e2e,scripts} and
 * the root scripts/. Not scanned: vendored code with its own license (packages/relay/src/vendor),
 * generated code (paraglide, .svelte-kit, build output) and the upstream Flotilla files in
 * packages/team-client (MIT, see its UPSTREAM.md); only team-client's Beamhop-owned
 * src/beamhop and scripts/beamhop are checked there.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

export const REPO_ROOT = join(import.meta.dir, '..', '..');
export const SPDX = 'SPDX-License-Identifier: AGPL-3.0-or-later';
const EXT = /\.(ts|tsx|js|mjs|cjs|svelte)$/;
const DIRS = ['src', 'test', 'e2e', 'scripts'];

/** Paths (relative, `/`-separated) that are never scanned. */
export const EXCLUDE: RegExp[] = [
  /(^|\/)node_modules\//,
  /(^|\/)\.svelte-kit\//,
  /(^|\/)(build|dist|coverage|test-results|playwright-report)\//,
  /\.d\.ts$/,
  // Vendored, own license (hoytech/negentropy, MIT).
  /^packages\/relay\/src\/vendor\//,
  // Generated by paraglide from messages/*.json.
  /^packages\/pwa\/src\/lib\/paraglide\//,
];

/** Roots for packages/team-client: only the Beamhop-owned parts of the Flotilla fork. */
const TEAM_CLIENT_OWNED = ['src/beamhop', 'scripts/beamhop'];

function walk(dir: string, out: string[]): void {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === '.svelte-kit') continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, out);
    else if (EXT.test(name)) out.push(path);
  }
}

export function candidateFiles(root = REPO_ROOT): string[] {
  const files: string[] = [];
  walk(join(root, 'scripts'), files);
  for (const pkg of readdirSync(join(root, 'packages'))) {
    const base = join(root, 'packages', pkg);
    if (!statSync(base).isDirectory()) continue;
    const dirs = pkg === 'team-client' ? TEAM_CLIENT_OWNED : DIRS;
    for (const d of dirs) walk(join(base, d), files);
  }
  return files
    .map((f) => relative(root, f).split('\\').join('/'))
    .filter((f) => !EXCLUDE.some((r) => r.test(f)))
    .sort();
}

/** True when the identifier is in the first lines (after an optional shebang). */
export function hasHeader(text: string): boolean {
  return text
    .split('\n')
    .slice(0, 5)
    .some((l) => l.includes(SPDX));
}

/** The header line in the file's comment syntax. */
export function headerFor(file: string): string {
  return file.endsWith('.svelte') ? `<!-- ${SPDX} -->` : `// ${SPDX}`;
}

export function addHeader(file: string, text: string): string {
  const header = headerFor(file);
  if (text.startsWith('#!')) {
    const nl = text.indexOf('\n');
    return `${text.slice(0, nl + 1)}${header}\n${text.slice(nl + 1)}`;
  }
  return `${header}\n${text}`;
}

/** Other agents/owners fix these themselves; `--fix` leaves them alone. */
const NO_AUTOFIX = /^packages\/(pwa|team-client)\//;

if (import.meta.main) {
  const fix = process.argv.includes('--fix');
  const files = candidateFiles();
  const missing = files.filter((f) => !hasHeader(readFileSync(join(REPO_ROOT, f), 'utf8')));
  const remaining: string[] = [];
  for (const f of missing) {
    if (fix && !NO_AUTOFIX.test(f)) {
      const path = join(REPO_ROOT, f);
      writeFileSync(path, addHeader(f, readFileSync(path, 'utf8')));
      console.log(`  fixed ${f}`);
    } else remaining.push(f);
  }
  console.log(`SPDX: checked ${files.length} files`);
  if (remaining.length > 0) {
    console.error(`${remaining.length} file(s) without "${SPDX}":`);
    for (const f of remaining) console.error(`  ${f}`);
    console.error('Add the header as the first line (see CONTRIBUTING.md).');
    process.exit(1);
  }
}
