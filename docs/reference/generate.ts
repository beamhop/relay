/**
 * Generates the reference pages from the code, so they never drift:
 *
 *   docs/reference/config.md   ← core `ConfigSchema` (+ every module's `configSchema`):
 *                                plain-language `.describe()` texts and `technical()` notes
 *   docs/reference/actions.md  ← the action registry of a fully loaded kernel (every built-in
 *                                and optional module registered in-process on memory ports)
 *
 *   bun docs/reference/generate.ts            # write both files
 *   bun docs/reference/generate.ts --check    # exit 1 if they are out of date (CI)
 *
 * The admin API reference is served live at /api/v1/openapi.json; the CLI reference is
 * `beamhop --help` / `beamhop <group> --help` (both generated from the same registry).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  type ActionDef,
  type BeamhopModule,
  ConfigSchema,
  createKernel,
  parseConfig,
  technicalNote,
} from '../../packages/core/src/index.ts';
import { DEFAULT_MODULE_PACKAGES, loadModules } from '../../packages/runtime-bun/src/index.ts';
import { memoryPorts } from '../../packages/testkit/src/index.ts';

/** zod's ZodType, taken from core (zod is not a root dependency). */
type ZodType = Parameters<typeof technicalNote>[0];

const OUT = import.meta.dir;
const HEADER = (what: string, from: string) =>
  `<!-- Generated by docs/reference/generate.ts from ${from}. Do not edit by hand. -->\n\n# ${what}\n\n`;

// ── zod introspection (zod 4 internals: `_zod.def`) ─────────────────────────
interface Def {
  type: string;
  innerType?: ZodType;
  defaultValue?: unknown;
  shape?: Record<string, ZodType>;
  element?: ZodType;
  entries?: Record<string, string | number>;
  values?: unknown[];
  options?: ZodType[];
  valueType?: ZodType;
  in?: ZodType;
  out?: ZodType;
}
const defOf = (s: ZodType) => (s as unknown as { _zod: { def: Def } })._zod.def;
const descOf = (s: ZodType) => (s as unknown as { description?: string }).description;

interface Unwrapped {
  core: ZodType;
  description?: string;
  technical?: string;
  defaultValue?: unknown;
  optional: boolean;
}

function unwrap(schema: ZodType): Unwrapped {
  let s = schema;
  const out: Unwrapped = { core: s, optional: false };
  for (let i = 0; i < 20; i++) {
    out.description ??= descOf(s);
    out.technical ??= technicalNote(s);
    const d = defOf(s);
    if (d.type === 'default' || d.type === 'prefault') {
      if (out.defaultValue === undefined) {
        try {
          out.defaultValue =
            typeof d.defaultValue === 'function' ? d.defaultValue() : d.defaultValue;
        } catch {
          // dynamic default
        }
      }
      s = d.innerType!;
    } else if (d.type === 'optional' || d.type === 'nullable' || d.type === 'readonly') {
      if (d.type === 'optional') out.optional = true;
      s = d.innerType!;
    } else if (d.type === 'pipe') {
      s = d.in!;
    } else break;
  }
  out.core = s;
  return out;
}

function typeLabel(s: ZodType): string {
  const d = defOf(s);
  switch (d.type) {
    case 'enum':
      return Object.values(d.entries ?? {})
        .map((v) => `\`${v}\``)
        .join(' \\| ');
    case 'literal':
      return (d.values ?? []).map((v) => `\`${JSON.stringify(v)}\``).join(' \\| ');
    case 'array':
      return `list of ${typeLabel(unwrap(d.element!).core)}`;
    case 'record':
      return 'map';
    case 'object':
      return 'section';
    case 'union':
      return (d.options ?? []).map((o) => typeLabel(unwrap(o).core)).join(' or ');
    default:
      return d.type;
  }
}

function fmtDefault(v: unknown): string {
  if (v === undefined) return '';
  if (typeof v === 'object' && v !== null && !Array.isArray(v) && Object.keys(v).length === 0)
    return '';
  const s = JSON.stringify(v);
  return s.length > 60 ? `\`${s.slice(0, 57)}…\`` : `\`${s}\``;
}

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n+/g, ' ');

interface Row {
  path: string;
  type: string;
  def: string;
  text: string;
}

function walk(schema: ZodType, path: string, rows: Row[]): void {
  const u = unwrap(schema);
  const d = defOf(u.core);
  const text = [u.description, u.technical ? `*Technical:* ${u.technical}` : '']
    .filter(Boolean)
    .join(' ');
  if (d.type === 'object' && d.shape) {
    if (path && text) rows.push({ path, type: 'section', def: '', text });
    for (const [k, v] of Object.entries(d.shape)) walk(v, path ? `${path}.${k}` : k, rows);
    return;
  }
  if (d.type === 'array' && d.element) {
    const el = unwrap(d.element);
    const elDef = defOf(el.core);
    if (elDef.type === 'object' || elDef.type === 'union') {
      rows.push({ path, type: 'list', def: fmtDefault(u.defaultValue), text });
      walkItem(el.core, `${path}[]`, rows);
      return;
    }
  }
  if (d.type === 'record' && path === 'modules') return; // documented per module below
  rows.push({ path, type: typeLabel(u.core), def: fmtDefault(u.defaultValue), text });
}

function walkItem(s: ZodType, path: string, rows: Row[]): void {
  const d = defOf(s);
  if (d.type === 'union' && d.options) {
    for (const opt of d.options) {
      const shape = defOf(unwrap(opt).core).shape ?? {};
      const disc = Object.entries(shape).find(([, v]) => defOf(unwrap(v).core).type === 'literal');
      const label = disc
        ? `${disc[0]}=${(defOf(unwrap(disc[1]).core).values ?? [])[0]}`
        : 'variant';
      walk(opt, `${path}(${label})`, rows);
    }
    return;
  }
  walk(s, path, rows);
}

function table(rows: Row[], envPrefix?: string): string {
  const lines = ['| Setting | Type | Default | Description |', '|---|---|---|---|'];
  for (const r of rows) {
    const env =
      envPrefix !== undefined && !r.path.includes('[]')
        ? `<br><sub>env \`BEAMHOP_${envPrefix}${r.path
            .split('.')
            .map((p) => p.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase())
            .join('__')}\`</sub>`
        : '';
    lines.push(`| \`${r.path}\`${env} | ${r.type} | ${r.def} | ${esc(r.text)} |`);
  }
  return `${lines.join('\n')}\n`;
}

// ── fully loaded kernel ─────────────────────────────────────────────────────
async function allModules(): Promise<BeamhopModule[]> {
  // Every package, including opt-in and conditional ones, as if all features were turned on.
  const packages = DEFAULT_MODULE_PACKAGES.map((p) => ({ ...p, when: undefined, optIn: false }));
  const quiet = memoryPorts().logger;
  return loadModules(parseConfig({}), quiet, packages);
}

async function loadKernel(modules: BeamhopModule[]) {
  const config = parseConfig({
    relays: [{ id: 'main', hosts: ['relay.example.com'] }],
    ai: { enabled: true, baseUrl: 'http://127.0.0.1:11434/v1', model: 'llama3' },
    plugins: [],
    modules: Object.fromEntries(modules.map((m) => [m.id, {}])),
  });
  // Register only: no background jobs, no network.
  const registerOnly = modules.map((m) => ({ ...m, start: undefined, stop: undefined }));
  return createKernel({ runtime: 'bun', ports: memoryPorts(), config, modules: registerOnly });
}

// ── pages ───────────────────────────────────────────────────────────────────
export async function configPage(modules: BeamhopModule[]): Promise<string> {
  const rows: Row[] = [];
  walk(ConfigSchema as unknown as ZodType, '', rows);
  let md = `${HEADER('Settings reference', 'the zod config schema (packages/core/src/config.ts and each module)')}`;
  md +=
    'Every setting can be changed in the admin app (with preview and undo), in `beamhop.yaml`, or ' +
    'with an environment variable: `BEAMHOP_` + the path in upper case, `__` between levels ' +
    '(e.g. `node.tls.mode` → `BEAMHOP_NODE__TLS__MODE`). Lists such as `relays` are set in the ' +
    'file or the app. Most people only ever touch the setup wizard; the rest is here for reference.\n\n';
  md += '## Core settings\n\n';
  md += table(rows, '');
  const withSchema = modules.filter((m) => m.configSchema).sort((a, b) => a.id.localeCompare(b.id));
  if (withSchema.length) {
    md +=
      '\n## Feature settings (`modules.<id>`)\n\nEach section exists only when that feature is ' +
      'turned on; enterprise features are invisible until enabled.\n';
    for (const m of withSchema) {
      const r: Row[] = [];
      walk(m.configSchema!, '', r);
      md += `\n### \`modules.${m.id}\`\n\n`;
      md += r.length ? table(r) : '_No settings._\n';
    }
  }
  return md;
}

function inputRows(def: ActionDef): Row[] {
  const rows: Row[] = [];
  const core = unwrap(def.input as ZodType).core;
  if (defOf(core).type === 'object') walk(core, '', rows);
  else rows.push({ path: '(input)', type: typeLabel(core), def: '', text: '' });
  return rows;
}

export function actionsPage(defs: ActionDef[]): string {
  let md = HEADER('Actions reference', 'the action registry of a fully loaded kernel');
  md +=
    'Every admin operation is an action. The admin app, the CLI (`beamhop <group> <name>`), the ' +
    'admin API (`POST /api/v1/nodes/self[/relays/<relay>]/actions/<id>`, see `/api/v1/openapi.json`), ' +
    'the command palette and NIP-86 all run these same actions. Changes show a preview first and ' +
    'can be undone where marked.\n\n';
  const groups = new Map<string, ActionDef[]>();
  for (const d of defs) {
    const g = d.id.split('.')[0] ?? d.id;
    groups.set(g, [...(groups.get(g) ?? []), d]);
  }
  md += `${[...groups.keys()].map((g) => `[${g}](#${g})`).join(' · ')}\n`;
  for (const [g, list] of groups) {
    md += `\n## ${g}\n`;
    for (const d of list) {
      const cli = `beamhop ${d.id.split('.').join(' ')}`;
      const flags = [
        d.readOnly ? 'read-only' : 'changes settings/data',
        d.undo ? 'undoable' : '',
        d.bulk ? 'bulk' : '',
        d.sensitive ? 'needs a second approver when approvals are on' : '',
      ].filter(Boolean);
      md += `\n### ${esc(d.title)}\n\n${esc(d.description)}\n\n`;
      md += `- **id:** \`${d.id}\` · **CLI:** \`${cli}\` · **scope:** ${d.scope} · **permission:** \`${d.permission}\`\n`;
      md += `- ${flags.join(' · ')}\n`;
      if (d.technical) md += `- *Technical:* ${esc(d.technical)}\n`;
      const rows = inputRows(d);
      if (rows.length) md += `\n${table(rows)}`;
    }
  }
  return md;
}

export async function generate(): Promise<Record<string, string>> {
  const modules = await allModules();
  const kernel = await loadKernel(modules);
  return {
    'config.md': await configPage(modules),
    'actions.md': actionsPage(kernel.actions.list()),
  };
}

if (import.meta.main) {
  const check = process.argv.includes('--check');
  const pages = await generate();
  let stale = false;
  for (const [file, text] of Object.entries(pages)) {
    const path = join(OUT, file);
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // new file
    }
    if (current === text) continue;
    if (check) {
      console.error(`${file} is out of date: run bun docs/reference/generate.ts`);
      stale = true;
    } else {
      writeFileSync(path, text);
      console.log(`wrote docs/reference/${file}`);
    }
  }
  // Modules may leave timers/sockets around; this is a one-shot generator.
  process.exit(stale ? 1 : 0);
}
