import { fileURLToPath } from "node:url";
import { readFileSync } from "node:fs";
import { test as base, expect, type Page } from "@playwright/test";

export const PORT = Number(process.env.E2E_PORT ?? 3399);
export const stateFile = fileURLToPath(new URL(`../.tmp/${PORT}/owner-state.json`, import.meta.url));

export interface Owner {
  http: string;
  ws: string;
  nsec: string;
  npub: string;
  skHex: string;
  pubkey: string;
}

export const owner = (): Owner => JSON.parse(readFileSync(fileURLToPath(new URL(`../.tmp/${PORT}/owner.json`, import.meta.url)), "utf8"));

/** Signs in through the login page with a private key (the throwaway owner key generated by harness/serve.ts). */
export async function loginWithKey(page: Page, nsec = owner().nsec) {
  await page.goto("login");
  await page.getByRole("tab", { name: "Key", exact: true }).click();
  await page.getByLabel("Private key").fill(nsec);
  await page.getByRole("button", { name: /sign in with (private )?key/i }).click();
  await page.waitForURL((u) => !u.pathname.endsWith("/login"));
}

/** Fails the test on uncaught page errors and console errors (React warnings, unhandled rejections). */
export const test = base.extend<{ consoleGuard: void }>({
  consoleGuard: [
    async ({ page }, use) => {
      const errors: string[] = [];
      page.on("pageerror", (e) => errors.push(`pageerror: ${e.message}`));
      page.on("console", (m) => {
        if (m.type() !== "error") return;
        const t = m.text();
        // expected: failed requests the test provokes on purpose (401/403/4xx) are logged by the browser
        if (/Failed to load resource: the server responded with a status of (4\d\d)/.test(t)) return;
        errors.push(`console.error: ${t}`);
      });
      await use();
      expect(errors, errors.join("\n")).toEqual([]);
    },
    { auto: true },
  ],
});
export { expect };
