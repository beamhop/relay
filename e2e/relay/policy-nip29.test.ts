/** NIP-29 relay-based groups: control events, resulting relay-signed group state, and read/write gating. */
import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import type { Event } from "nostr-tools";
import { startRelay, type Relay } from "../harness/relay";
import { RelayClient, newUser, now, sign } from "../harness/client";
import { connectAs, connectAuthed, nextSub, nip11, ownerApi, uniqueIp, withSettings } from "./policy-helpers";

let relay: Relay;
let self: string; // relay pubkey (signs 39000-39003)
let reader: RelayClient;
beforeAll(async () => {
  // per-test client addresses: group creation is rate limited per address
  relay = await startRelay({ overrides: { server: { trustProxy: true } } });
  self = (await nip11(relay)).self;
  reader = await connectAs(relay, uniqueIp());
});
afterAll(async () => {
  reader?.close();
  await relay?.stop();
});

let gseq = 0;
const gid = () => `g${Date.now().toString(36)}${++gseq}`;
type User = ReturnType<typeof newUser>;

async function createGroup(c: RelayClient, admin: User, flags: string[] = [], id = gid()) {
  const ev = sign(admin.sk, { kind: 9007, tags: [["h", id], ["name", `Group ${id}`], ...flags.map((f) => [f])] });
  const r = await c.publish(ev);
  expect(r).toEqual({ ok: true, message: "" });
  return id;
}

async function meta(kind: 39000 | 39001 | 39002 | 39003, id: string, via: RelayClient = reader): Promise<Event | undefined> {
  const { events } = await via.query(nextSub("meta"), [{ kinds: [kind], authors: [self], "#d": [id] }]);
  return events[0];
}
const pTags = (ev?: Event) => (ev?.tags ?? []).filter((t) => t[0] === "p").map((t) => t[1]);

const ctl = (u: User, kind: number, id: string, tags: string[][] = [], extra: { created_at?: number } = {}) =>
  sign(u.sk, { kind, content: Math.random().toString(36).slice(2), tags: [["h", id], ...tags], ...(extra.created_at ? { created_at: extra.created_at } : {}) });

describe("group creation and relay-signed state", () => {
  test("9007 creates a group; the relay publishes 39000-39003 with the creator as admin", async () => {
    const admin = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    const m = await meta(39000, id);
    expect(m?.pubkey).toBe(self);
    expect(m?.tags).toContainEqual(["name", `Group ${id}`]);
    const admins = await meta(39001, id);
    expect(admins?.tags).toContainEqual(["p", admin.pubkey, "admin"]);
    expect(pTags(await meta(39002, id))).toEqual([admin.pubkey]);
    const roles = await meta(39003, id);
    expect(roles?.tags.filter((t) => t[0] === "role").map((t) => t[1]).sort()).toEqual(["admin", "moderator"]);
    expect((await ownerApi(relay, "GET", "/groups")).items.map((g: any) => g.id)).toContain(id);
    c.close();
  });

  test("creating an existing group or an invalid id is refused", async () => {
    const admin = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    const dup = await c.publish(sign(newUser().sk, { kind: 9007, tags: [["h", id]] }));
    expect(dup).toEqual({ ok: false, message: "duplicate: group already exists" });
    const bad = await c.publish(sign(admin.sk, { kind: 9007, tags: [["h", "bad id!"]] }));
    expect(bad.message).toStartWith("invalid: group id must match");
    c.close();
  });

  test("clients cannot publish group metadata kinds", async () => {
    const c = await connectAs(relay, uniqueIp());
    const r = await c.publish(sign(newUser().sk, { kind: 39000, tags: [["d", gid()], ["name", "fake"]] }));
    expect(r).toEqual({ ok: false, message: "restricted: group metadata events are generated by the relay" });
    c.close();
  });

  test("groups.creation=admins: only relay staff can create groups", async () => {
    await withSettings(relay, { groups: { creation: "admins" } }, async () => {
      const c = await connectAs(relay, uniqueIp());
      const r = await c.publish(sign(newUser().sk, { kind: 9007, tags: [["h", gid()]] }));
      expect(r).toEqual({ ok: false, message: "restricted: you are not allowed to create groups on this relay" });
      await createGroup(c, { sk: relay.owner.sk, pubkey: relay.owner.pubkey });
      c.close();
    });
  });

  test("9002 edit-metadata by the group admin updates 39000 (and flags)", async () => {
    const admin = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    const r = await c.publish(ctl(admin, 9002, id, [["name", "Renamed"], ["about", "new about"], ["closed"]]));
    expect(r.ok).toBe(true);
    const m = await meta(39000, id);
    expect(m?.tags).toContainEqual(["name", "Renamed"]);
    expect(m?.tags).toContainEqual(["about", "new about"]);
    expect(m?.tags).toContainEqual(["closed"]);
    c.close();
  });
});

describe("group writes", () => {
  test("content for an unknown group is refused; an event naming two groups is invalid", async () => {
    const u = newUser();
    const c = await connectAs(relay, uniqueIp());
    expect(await c.publish(sign(u.sk, { kind: 9, content: "hi", tags: [["h", gid()]] }))).toEqual({ ok: false, message: "invalid: group not found" });
    const a = await createGroup(c, u);
    const b = await createGroup(c, u);
    const two = await c.publish(sign(u.sk, { kind: 9, content: "both", tags: [["h", a], ["h", b]] }));
    expect(two).toEqual({ ok: false, message: "invalid: an event may only reference one group (h tag)" });
    c.close();
  });

  test("open group: join (9021) adds the member, the relay emits a 9000 put-user and updates 39002", async () => {
    const admin = newUser();
    const joiner = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    expect((await c.publish(ctl(joiner, 9021, id))).ok).toBe(true);
    expect(pTags(await meta(39002, id))).toContain(joiner.pubkey);
    const { events } = await reader.query(nextSub(), [{ kinds: [9000], authors: [self], "#h": [id] }]);
    expect(events.some((e) => pTags(e).includes(joiner.pubkey))).toBe(true);
    const again = await c.publish(ctl(joiner, 9021, id));
    expect(again).toEqual({ ok: false, message: "duplicate: already a member of this group" });
    c.close();
  });

  test("restricted group: only members may post", async () => {
    const admin = newUser();
    const member = newUser();
    const outsider = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin, ["restricted"]);
    expect((await c.publish(ctl(admin, 9000, id, [["p", member.pubkey]]))).ok).toBe(true);
    expect((await c.publish(sign(member.sk, { kind: 9, content: "member post", tags: [["h", id]] }))).ok).toBe(true);
    const r = await c.publish(sign(outsider.sk, { kind: 9, content: "outsider post", tags: [["h", id]] }));
    expect(r).toEqual({ ok: false, message: "restricted: not a member of this group" });
    c.close();
  });

  test("closed group: join needs approval or a one-time invite code", async () => {
    const admin = newUser();
    const a = newUser();
    const b = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin, ["closed"]);
    expect(await c.publish(ctl(a, 9021, id))).toEqual({ ok: false, message: "restricted: join request pending admin approval" });
    expect((await c.publish(ctl(admin, 9009, id, [["code", "secret-code-1"]]))).ok).toBe(true);
    expect((await c.publish(ctl(a, 9021, id, [["code", "secret-code-1"]]))).ok).toBe(true);
    expect(pTags(await meta(39002, id))).toContain(a.pubkey);
    // the code was used up
    expect((await c.publish(ctl(b, 9021, id, [["code", "secret-code-1"]]))).message).toBe("restricted: join request pending admin approval");
    c.close();
  });

  test("moderation by a plain member is refused", async () => {
    const admin = newUser();
    const member = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    await c.publish(ctl(member, 9021, id));
    const r = await c.publish(ctl(member, 9000, id, [["p", newUser().pubkey]]));
    expect(r).toEqual({ ok: false, message: "restricted: insufficient group permissions" });
    const r2 = await c.publish(ctl(member, 9001, id, [["p", admin.pubkey]]));
    expect(r2.ok).toBe(false);
    c.close();
  });

  test("9001 remove-user by the admin removes a member (who can then no longer post in a restricted group)", async () => {
    const admin = newUser();
    const member = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin, ["restricted"]);
    await c.publish(ctl(admin, 9000, id, [["p", member.pubkey]]));
    expect(pTags(await meta(39002, id))).toContain(member.pubkey);
    expect((await c.publish(ctl(admin, 9001, id, [["p", member.pubkey]]))).ok).toBe(true);
    expect(pTags(await meta(39002, id))).not.toContain(member.pubkey);
    expect((await c.publish(sign(member.sk, { kind: 9, content: "still here?", tags: [["h", id]] }))).message).toBe("restricted: not a member of this group");
    c.close();
  });

  test("9022 leave removes the member", async () => {
    const admin = newUser();
    const member = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    await c.publish(ctl(member, 9021, id));
    expect((await c.publish(ctl(member, 9022, id))).ok).toBe(true);
    expect(pTags(await meta(39002, id))).not.toContain(member.pubkey);
    expect((await c.publish(ctl(member, 9022, id))).message).toBe("invalid: not a member of this group");
    c.close();
  });

  test("9005 delete-event removes group content and it can't be re-published", async () => {
    const admin = newUser();
    const member = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    await c.publish(ctl(member, 9021, id));
    const post = sign(member.sk, { kind: 9, content: "to be removed", tags: [["h", id]] });
    expect((await c.publish(post)).ok).toBe(true);
    expect((await c.publish(ctl(admin, 9005, id, [["e", post.id]]))).ok).toBe(true);
    expect((await reader.query(nextSub(), [{ ids: [post.id] }])).events).toEqual([]);
    const again = await c.publish(post);
    expect(again.ok).toBe(false);
    expect(again.message).toStartWith("blocked:");
    c.close();
  });

  test("relay staff can moderate any group", async () => {
    const admin = newUser();
    const member = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    await c.publish(ctl(member, 9021, id));
    const owner = { sk: relay.owner.sk, pubkey: relay.owner.pubkey };
    expect((await c.publish(ctl(owner, 9001, id, [["p", member.pubkey]]))).ok).toBe(true);
    expect(pTags(await meta(39002, id))).not.toContain(member.pubkey);
    c.close();
  });

  test("control events older than 10 minutes are refused (late publication)", async () => {
    const admin = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    const r = await c.publish(ctl(admin, 9000, id, [["p", newUser().pubkey]], { created_at: now() - 700 }));
    expect(r).toEqual({ ok: false, message: "invalid: group control events must be recent (late publication)" });
    c.close();
  });

  test("9008 delete-group purges its events and forgets the group", async () => {
    const admin = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    const post = sign(admin.sk, { kind: 9, content: "bye", tags: [["h", id]] });
    await c.publish(post);
    expect((await c.publish(ctl(admin, 9008, id))).ok).toBe(true);
    expect((await reader.query(nextSub(), [{ "#h": [id] }])).events).toEqual([]);
    expect(await meta(39000, id)).toBeUndefined();
    expect((await c.publish(sign(admin.sk, { kind: 9, content: "again", tags: [["h", id]] }))).message).toBe("invalid: group not found");
    expect((await ownerApi(relay, "GET", "/groups")).items.map((g: any) => g.id)).not.toContain(id);
    c.close();
  });

  test("admin API DELETE /groups/:id removes the group", async () => {
    const admin = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin);
    const detail = await ownerApi(relay, "GET", `/groups/${id}`);
    expect(detail.memberList).toEqual([{ pubkey: admin.pubkey, roles: ["admin"] }]);
    await ownerApi(relay, "DELETE", `/groups/${id}`);
    expect((await c.publish(sign(admin.sk, { kind: 9, content: "x", tags: [["h", id]] }))).message).toBe("invalid: group not found");
    c.close();
  });
});

describe("group read visibility", () => {
  test("private group content is only delivered to authenticated members", async () => {
    const admin = newUser();
    const outsider = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin, ["private"]);
    const post = sign(admin.sk, { kind: 9, content: "secret", tags: [["h", id]] });
    expect((await c.publish(post)).ok).toBe(true);
    expect((await reader.query(nextSub(), [{ "#h": [id], kinds: [9] }])).events).toEqual([]);
    const out = await connectAuthed(relay, outsider.sk, uniqueIp());
    expect((await out.query(nextSub(), [{ ids: [post.id] }])).events).toEqual([]);
    const mem = await connectAuthed(relay, admin.sk, uniqueIp());
    expect((await mem.query(nextSub(), [{ ids: [post.id] }])).events.map((e) => e.id)).toEqual([post.id]);
    // COUNT on a private group needs membership
    const cs = nextSub();
    reader.send(["COUNT", cs, { "#h": [id] }]);
    const m = await reader.waitFor((f) => f[1] === cs);
    expect(m[0]).toBe("CLOSED");
    expect(m[2]).toBe("auth-required: this group is private");
    for (const x of [c, out, mem]) x.close();
  });

  test("private group live events reach members but not outsiders", async () => {
    const admin = newUser();
    const member = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin, ["private"]);
    await c.publish(ctl(admin, 9000, id, [["p", member.pubkey]]));
    const mem = await connectAuthed(relay, member.sk, uniqueIp());
    const out = await connectAuthed(relay, newUser().sk, uniqueIp());
    const sm = nextSub();
    const so = nextSub();
    await mem.query(sm, [{ "#h": [id], kinds: [9] }], false);
    await out.query(so, [{ "#h": [id], kinds: [9] }], false);
    const post = sign(admin.sk, { kind: 9, content: "live secret", tags: [["h", id]] });
    await c.publish(post);
    await mem.waitFor((f) => f[0] === "EVENT" && f[1] === sm && (f[2] as Event).id === post.id);
    await out.expectNone((f) => f[0] === "EVENT" && f[1] === so, 200);
    for (const x of [c, mem, out]) x.close();
  });

  test("hidden group metadata is not served to non-members", async () => {
    const admin = newUser();
    const c = await connectAs(relay, uniqueIp());
    const id = await createGroup(c, admin, ["hidden"]);
    expect(await meta(39000, id)).toBeUndefined();
    const mem = await connectAuthed(relay, admin.sk, uniqueIp());
    expect((await meta(39000, id, mem))?.tags).toContainEqual(["hidden"]);
    c.close();
    mem.close();
  });
});
